import {test,expect} from '@playwright/test';
import {totpAt} from '../../services/api/src/phase71/mfa-core';
test('account enrols MFA then requires recovery code after logout',async({page})=>{
  test.setTimeout(100_000);
  const email=`phase71-${Date.now()}-${Math.random().toString(36).slice(2,6)}@example.test`;
  const password='really long unique passphrase learning 2026';
  await page.goto('/#account');
  await page.getByRole('button',{name:'Create account'}).click();
  await page.getByPlaceholder('your@email.com').fill(email);
  await page.locator('input[type="password"]').first().fill(password);
  await page.getByRole('button',{name:'Create private account'}).click();
  await expect(page.getByRole('button',{name:'Begin MFA setup'})).toBeVisible();
  await page.getByLabel('Confirm password for MFA').fill(password);
  await page.getByRole('button',{name:'Begin MFA setup'}).click();
  const secret=(await page.getByTestId('mfa-secret').innerText()).trim();
  const code=totpAt(secret,Math.floor(Date.now()/30_000));
  await page.getByLabel('Confirm MFA setup code').fill(code);
  await page.getByRole('button',{name:'Activate MFA'}).click();
  await expect(page.getByTestId('mfa-recovery')).toBeVisible();
  const codes=(await page.getByTestId('mfa-recovery').innerText()).trim().split('\n');
  expect(codes).toHaveLength(8);
  await page.getByRole('button',{name:'I saved my recovery codes'}).click();
  await page.getByRole('button',{name:/Use cloud records on this device/}).click();
  await expect(page.getByRole('button',{name:/Learning records: Connected/})).toBeVisible({timeout:30_000});
  await page.getByRole('button',{name:/Sign out and clear local account cache/}).click();
  await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
  await page.getByPlaceholder('your@email.com').fill(email);
  await page.locator('input[type="password"]').fill(password);
  await page.getByRole('button',{name:'Sign in to PostgreSQL'}).click();
  await expect(page.getByRole('button',{name:'Verify MFA and sign in'})).toBeVisible();
  await page.getByLabel('MFA verification code').fill(codes[0]);
  await page.getByRole('button',{name:'Verify MFA and sign in'}).click();
  await expect(page.getByRole('heading',{name:'Choose where to begin'})).toBeVisible();
  await page.getByRole('button',{name:/Use cloud records on this device/}).click();
  await expect(page.getByRole('button',{name:/Learning records: Connected/})).toBeVisible({timeout:30_000});
});
